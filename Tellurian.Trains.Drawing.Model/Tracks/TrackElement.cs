using System.Text.Json.Serialization;
using Tellurian.Trains.Drawing.Geometry;

namespace Tellurian.Trains.Drawing.Model.Tracks;

/// <summary>
/// A parametric track element in a module's track plan (spec MD-6), in module coordinates.
/// Each element produces the centre lines of its routes and its connection points.
/// A connection point's heading points out of the element, like an exit pose.
/// </summary>
[JsonPolymorphic(TypeDiscriminatorPropertyName = "type")]
[JsonDerivedType(typeof(StraightTrack), "straight")]
[JsonDerivedType(typeof(CurvedTrack), "curve")]
[JsonDerivedType(typeof(FlexTrack), "flex")]
[JsonDerivedType(typeof(Turnout), "turnout")]
[JsonDerivedType(typeof(Crossing), "crossing")]
[JsonDerivedType(typeof(DoubleSlip), "doubleSlip")]
[JsonDerivedType(typeof(BufferStop), "bufferStop")]
public abstract record TrackElement
{
    public Guid Id { get; init; } = Guid.NewGuid();

    /// <summary>Track designation, e.g. "1" or "Main" (spec MD-8).</summary>
    public string? Designation { get; init; }

    public bool IsMainTrack { get; init; }

    /// <summary>Narrow-gauge track, drawn in a lighter tint (spec MD-21).</summary>
    public bool IsNarrowGauge { get; init; }

    /// <summary>True for through tracks generated by auto-draw; false once detached or drawn by hand.</summary>
    public bool IsGenerated { get; init; }

    /// <summary>The centre lines of all routes through the element.</summary>
    public abstract IReadOnlyList<SegmentPath> Routes();

    /// <summary>The points where other elements or exits connect, headings pointing out of the element.</summary>
    public abstract IReadOnlyList<Pose> ConnectionPoints();

    /// <summary>The sum of the route lengths. Parts shared by several routes, such as the points of a turnout, count once per route.</summary>
    public virtual double TrackLength => Routes().Sum(r => r.Length);
}
